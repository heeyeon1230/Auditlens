def write_ground_truth(vouchers, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    by_case = {}
    for v in vouchers:
        if v["case"]:
            by_case.setdefault(v["case"], []).append(v)
    rows = []
    for cid, (rule, sub, kind, desc, reason, expected, others, where) in CASES.items():
        base = {"사례ID": cid, "규칙": rule, "세부 조건": sub, "사례 구분": kind, "사례 설명": desc,
                "탐지 근거": reason, "예상 결과": expected, "다른 규칙(예상)": others, "확인 위치": where}
        if cid in PERIOD_TARGETS:
            members = by_case.get(cid, [])
            rows.append({**base, "단위": "계정-월", "대상": PERIOD_TARGETS[cid],
                         "회계처리일": "", "계정": PERIOD_TARGETS[cid].rsplit(" ", 1)[0], "거래처": "",
                         "전표 금액": "", "사례 설명": desc + (f" (이 달 사례 전표 {len(members)}개)" if members else "")})
            continue
        members = by_case.get(cid, [])
        if not members:
            raise ValueError(f"사례 {cid}에 해당하는 전표가 없습니다")
        for v in members:
            accounts = ", ".join(dict.fromkeys(l[0] for l in v["lines"]))
            rows.append({**base, "단위": "전표", "대상": v["je_id"], "회계처리일": v["posting"].isoformat(),
                         "계정": accounts, "거래처": v["vendor"], "전표 금액": sum(l[1] for l in v["lines"])})
    unknown = set(by_case) - set(CASES)
    if unknown:
        raise ValueError(f"정의되지 않은 사례: {unknown}")
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    return rows
